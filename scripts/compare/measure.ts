// What a compared build ships: bytes by file type, by the package that wrote them, and along its load paths.
import { existsSync } from "node:fs";
import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import { brotliCompressSync, gzipSync } from "node:zlib";

export type Sizes = { raw: number; gzip: number; brotli: number };

const sizesOf = (content: Buffer | string): Sizes => ({
  raw: Buffer.byteLength(content),
  gzip: gzipSync(content, { level: 9 }).length,
  brotli: brotliCompressSync(content).length,
});
const add = (a: Sizes, b: Sizes): Sizes => ({ raw: a.raw + b.raw, gzip: a.gzip + b.gzip, brotli: a.brotli + b.brotli });
const ZERO: Sizes = { raw: 0, gzip: 0, brotli: 0 };

// Each file is a separate response, so a total adds up each file's own compressed size.
export async function measureFiles(dir: string, extension: string): Promise<Sizes & { files: number }> {
  let total = { ...ZERO, files: 0 };
  for (const file of await readdir(dir, { recursive: true, withFileTypes: true })) {
    if (!file.isFile() || !file.name.endsWith(extension)) continue;
    total = { ...add(total, sizesOf(await readFile(path.join(file.parentPath, file.name)))), files: total.files + 1 };
  }
  return total;
}

// Who wrote the minified JS: React (react, react-dom, scheduler), the styling library (every other package, and code a
// library generates into the app, such as Panda's styled-system), the app's own modules, and the bundler's helpers.
export type Owner = "react" | "library" | "app" | "bundler";
export type Attribution = Record<Owner, number> & {
  // The library's bytes gzipped on their own: an estimate, since in the build they share a gzip stream with the rest.
  libraryGzip: number;
  packages: Record<string, number>;
};

const REACT = new Set(["react", "react-dom", "scheduler"]);

function ownerOf(source: string): { owner: Owner; name: string } {
  const pkg = /.*node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(source)?.[1];
  if (pkg) return { owner: REACT.has(pkg) ? "react" : "library", name: pkg };
  if (source.includes("packages/nishiki/")) return { owner: "library", name: "@nishikijs/react" };
  if (source.includes("styled-system/")) return { owner: "library", name: "styled-system (generated by Panda)" };
  if (/(^|\/)apps\/[^/]+\/src\//.test(source)) return { owner: "app", name: "app" };
  return { owner: "bundler", name: "bundler" };
}

const BASE64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

// Source map segments of each generated line, as [column, source]. Code a plugin inserted without mapping it, such as
// compiled style data, has segments without a source; it is taken to belong to the module mapped before it, and
// code before any mapped segment, such as the bundler's runtime helpers, to no source (-1). The last segment of a line
// also owns the start of the next line, up to that line's first segment: a template literal, such as React's
// multi-line error messages, goes on there without a segment of its own.
function decodeMappings(mappings: string): [number, number][][] {
  const lines: [number, number][][] = [];
  let source = -1;
  const state = [0, 0, 0, 0, 0];
  for (const line of mappings.split(";")) {
    const segments: [number, number][] = [];
    state[0] = 0;
    for (const segment of line.split(",")) {
      if (!segment) continue;
      const fields: number[] = [];
      let value = 0;
      let shift = 0;
      for (const char of segment) {
        const digit = BASE64.indexOf(char);
        value += (digit & 31) << shift;
        if (digit & 32) shift += 5;
        else {
          fields.push(value & 1 ? -(value >>> 1) : value >>> 1);
          value = 0;
          shift = 0;
        }
      }
      fields.forEach((field, index) => (state[index] = state[index]! + field));
      if (fields.length > 1) source = state[1]!;
      segments.push([state[0]!, source]);
    }
    lines.push(segments.sort(([a], [b]) => a - b));
  }
  return lines;
}

export async function attribute(dir: string): Promise<Attribution> {
  const result: Attribution = { react: 0, library: 0, app: 0, bundler: 0, libraryGzip: 0, packages: {} };
  const library: string[] = [];
  for (const file of await readdir(dir, { recursive: true, withFileTypes: true })) {
    if (!file.isFile() || !file.name.endsWith(".js")) continue;
    const code = await readFile(path.join(file.parentPath, file.name), "utf8");
    const mapFile = path.join(file.parentPath, `${file.name}.map`);
    if (!existsSync(mapFile)) throw new Error(`${mapFile} is missing; the builds need hidden source maps`);
    const map: { sources: string[]; mappings: string } = JSON.parse(await readFile(mapFile, "utf8"));
    const owners = map.sources.map(ownerOf);
    const lines = decodeMappings(map.mappings);
    code.split("\n").forEach((text, index) => {
      const segments = lines[index] ?? [];
      const spans: [number, number, number][] = [
        [0, segments[0]?.[0] ?? text.length, lines[index - 1]?.at(-1)?.[1] ?? -1],
      ];
      segments.forEach(([column, source], i) => spans.push([column, segments[i + 1]?.[0] ?? text.length, source]));
      for (const [start, end, source] of spans) {
        if (end <= start) continue;
        const slice = text.slice(start, end);
        const bytes = Buffer.byteLength(slice);
        const { owner, name } = source === -1 ? { owner: "bundler" as const, name: "bundler" } : owners[source]!;
        result[owner] += bytes;
        result.packages[name] = (result.packages[name] ?? 0) + bytes;
        if (owner === "library") library.push(slice);
      }
    });
  }
  result.libraryGzip = library.length ? gzipSync(library.join(""), { level: 9 }).length : 0;
  return result;
}

type Manifest = Record<
  string,
  { file: string; css?: string[]; imports?: string[]; dynamicImports?: string[]; isEntry?: boolean }
>;

export type Load = { js: number; css: number; html: number; total: number; jsRequests: number; cssRequests: number };
export type LoadPaths = {
  firstLoad: Load;
  // From the first page to each lazily loaded route: what that navigation fetches on top of the first load.
  navigation: { mean: Load; worst: Load; count: number };
  // Everything a visit to every route fetches.
  visitAll: Load;
};

// Gzip sizes along the load paths Vite's manifest records: the HTML entry's static imports on first load, then one
// dynamic import at a time.
export async function loadPaths(dir: string): Promise<LoadPaths> {
  const manifest: Manifest = JSON.parse(await readFile(path.join(dir, ".vite/manifest.json"), "utf8"));
  const gzip = new Map<string, number>();
  const gzipOf = async (file: string) => {
    let size = gzip.get(file);
    if (size === undefined) {
      size = gzipSync(await readFile(path.join(dir, file)), { level: 9 }).length;
      gzip.set(file, size);
    }
    return size;
  };
  const closureOf = (keys: Iterable<string>) => {
    const closure = new Set(keys);
    for (const key of closure) for (const imported of manifest[key]!.imports ?? []) closure.add(imported);
    return closure;
  };
  const filesOf = (keys: Iterable<string>) => {
    const files = new Set<string>();
    for (const key of keys) {
      files.add(manifest[key]!.file);
      for (const css of manifest[key]!.css ?? []) files.add(css);
    }
    return files;
  };
  const loadOf = async (files: Iterable<string>, html = 0): Promise<Load> => {
    const load: Load = { js: 0, css: 0, html, total: html, jsRequests: 0, cssRequests: 0 };
    for (const file of files) {
      const size = await gzipOf(file);
      if (file.endsWith(".css")) {
        load.css += size;
        load.cssRequests++;
      } else if (file.endsWith(".js")) {
        load.js += size;
        load.jsRequests++;
      }
      load.total += size;
    }
    return load;
  };

  const entries = Object.keys(manifest).filter((key) => manifest[key]!.isEntry);
  if (entries.length !== 1) throw new Error(`${dir} has ${entries.length} entries; expected one`);
  const entry = entries[0]!;
  const html = gzipSync(await readFile(path.join(dir, "index.html")), { level: 9 }).length;
  const first = closureOf([entry]);
  const firstFiles = filesOf(first);
  const navigations: Load[] = [];
  const visited = new Set(firstFiles);
  for (const key of first) {
    for (const target of manifest[key]!.dynamicImports ?? []) {
      const files = [...filesOf(closureOf([target]))].filter((file) => !firstFiles.has(file));
      for (const file of files) visited.add(file);
      navigations.push(await loadOf(files));
    }
  }
  const mean = (key: keyof Load) => navigations.reduce((sum, load) => sum + load[key], 0) / (navigations.length || 1);
  const worst = navigations.reduce((a, b) => (b.total > a.total ? b : a), navigations[0]!);
  return {
    firstLoad: await loadOf(firstFiles, html),
    navigation: {
      mean: {
        js: mean("js"),
        css: mean("css"),
        html: 0,
        total: mean("total"),
        jsRequests: mean("jsRequests"),
        cssRequests: mean("cssRequests"),
      },
      worst,
      count: navigations.length,
    },
    visitAll: await loadOf(visited, html),
  };
}
